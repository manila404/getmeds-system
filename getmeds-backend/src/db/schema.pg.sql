-- PostgreSQL port of schema.sql.
--
-- Sep 2, 2026. Deliberately NOT idiomatic Postgres. The rule followed
-- throughout is: change the dialect, not the data shapes — because 420 tests
-- and 183 query sites assert against the shapes SQLite produced, and a port
-- that also "improves" them stops being reviewable.
--
-- The three that matter, and why:
--
--   REAL -> DOUBLE PRECISION, not NUMERIC.
--     NUMERIC is the correct type for money and this schema should eventually
--     use it. But node-postgres returns NUMERIC as a STRING (arbitrary
--     precision cannot fit a JS number), so `total_amount` would come back
--     "1500.00" instead of 1500, and every assertion and arithmetic operation
--     on it would silently change behaviour. Port first, fix money later, as
--     its own change with its own tests.
--
--   Booleans stay INTEGER.
--     is_active, is_read, is_test_account are 0/1 and the tests assert
--     `toBe(1)`. A real BOOLEAN would return true/false and break them all
--     for no functional gain during a port.
--
--   Timestamps stay TEXT holding ISO-8601.
--     The app writes `new Date().toISOString()` and the code SORTS AND
--     COMPARES these as strings (e.g. next_attempt_at <= ?, ORDER BY
--     created_at). A real timestamptz would be better, but mixing the two
--     during a port means string/timestamp comparisons that fail in
--     non-obvious ways. Note the default below reproduces JS's exact format,
--     including the T, the three fractional digits and the Z — a default of
--     now()::text would produce '2026-09-02 08:00:00.123456', which sorts
--     DIFFERENTLY as a string and would quietly corrupt every ordering.
--
-- AUTOINCREMENT -> GENERATED BY DEFAULT AS IDENTITY (not ALWAYS): tests and
-- fixtures sometimes insert explicit ids, which ALWAYS would reject.

-- Matches JavaScript's Date.toISOString() exactly: 2026-09-02T08:00:00.123Z
CREATE OR REPLACE FUNCTION iso_now() RETURNS TEXT
  LANGUAGE sql STABLE AS
$$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') $$;


  -- One of auth.controller's DIVISIONS, matched against orders.division.
  division TEXT NOT NULL,
  -- NULL means the WHOLE division; a value narrows to that sub-division only.
  --
  -- Deliberately free text rather than an enum. B2B has no fixed sub-division
  -- list, and B2B -> NBD/CRR is precisely the case this column exists for --
  -- though as of today neither appears on any order, because B2B's Zoho
  -- Salesperson field holds a person's name where HOS holds a territory.
  sub_division TEXT,
  created_at TEXT NOT NULL,
  created_by INTEGER REFERENCES users(id)
);

-- The lookup is always "every rule for this user", on every scoped request.
CREATE INDEX IF NOT EXISTS idx_manager_order_scope_user ON manager_order_scope(user_id);

-- One rule per (user, division, sub-division). COALESCE because NULL is not
-- equal to NULL in a unique index, so without it a user could hold the same
-- whole-division grant many times over.
CREATE UNIQUE INDEX IF NOT EXISTS idx_manager_order_scope_unique
  ON manager_order_scope(user_id, division, COALESCE(sub_division, ''));

-- Scoped queries filter on division, and increasingly on both.
CREATE INDEX IF NOT EXISTS idx_orders_division ON orders(division);
CREATE INDEX IF NOT EXISTS idx_orders_division_sub ON orders(division, sub_division);

CREATE TABLE IF NOT EXISTS salesperson_mappings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- The Zoho string EXACTLY as it appears on the Sales Order, trailing spaces
  -- and all. Matching is done on a normalised form (see
  -- services/salespersonMappingService.js), but what is stored is verbatim, so
  -- this table can always be traced back to what Zoho actually holds.
  zoho_salesperson TEXT NOT NULL UNIQUE,
  -- The system account that owns orders carrying this string. NULL for
  -- anything that is not a person, and for people who have not signed up yet
  -- or have left — see `kind`.
  user_id INTEGER REFERENCES users(id),
  -- What this string turned out to BE. Roughly half of the 171 distinct
  -- values are not people at all: 51 are territories ('HOS | LAGUNA',
  -- 'B&B | EAST AVE'), 13 are sales channels ('WEB', 'Shopee', 'Lazada').
  -- Recording that is the difference between "nobody has looked at this yet"
  -- and "somebody looked, and there is no person to assign".
  --   undecided — not yet reviewed (the default for a newly discovered string)
  --   person    — a real rep; user_id names them, or is NULL if they have no
  --               account yet or have left the company
  --   territory — a branch/area, stays Management-owned
  --   channel   — WEB/Shopee/Lazada/etc, stays Management-owned
  --   vacant    — explicitly nobody ('HOS | MANILA VACANT')
  kind TEXT NOT NULL DEFAULT 'undecided'
    CHECK(kind IN ('undecided','person','territory','channel','vacant')),
  notes TEXT,
  mapped_by INTEGER REFERENCES users(id),
  mapped_at TEXT,
  created_at TEXT DEFAULT iso_now()
);

CREATE INDEX IF NOT EXISTS idx_salesperson_mappings_user ON salesperson_mappings(user_id);
CREATE INDEX IF NOT EXISTS idx_salesperson_mappings_kind ON salesperson_mappings(kind);


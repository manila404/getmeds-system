-- Proof of payment (Sep 4, 2026).
--
-- The deposit slip, transfer screenshot or receipt a MedRep attaches to an
-- order. It is the EVIDENCE Finance looks at when deciding the account check
-- at `ready_for_finance_verified` — the stage that already gates invoicing.
-- It is not a second decision beside that one.
--
-- Shaped deliberately like `payments` above: its own row, its own
-- pending/verified/rejected status, joined onto the order. It is NOT a
-- pipeline stage — `orders.status`, workflow/stateMachine.js and
-- services/orderCompletionService.js are all untouched by it. Making it a
-- status would have meant a CHECK migration and edits to every queue query,
-- which is the class of change 2026-09-01-status-rename.md documents going
-- wrong.
--
-- It is also NOT the same thing as `payments`. That table is Zoho's record of
-- a Customer Payment, arriving by webhook, and it is what
-- orderCompletionService.js means by "paid". This table is the customer's
-- CLAIM to have paid. A verified proof does not make an order paid.
--
-- `storage_path` is a key into the private Supabase Storage bucket, never a
-- URL: view URLs are signed on read with a short TTL and are not stored
-- anywhere. The file itself never passes through the API — the browser PUTs
-- it straight to Supabase against a signed upload URL, because Vercel caps
-- request bodies at 4.5 MB and a phone photo routinely exceeds that.
--
-- order_id is UNIQUE: one proof per order, matching payments and
-- dispatch_records. Re-uploading after a rejection upserts this row and
-- clears the verification columns rather than inserting a second one.
CREATE TABLE IF NOT EXISTS payment_proofs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER UNIQUE NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','verified','rejected')),
  storage_path TEXT NOT NULL,
  file_name TEXT,
  content_type TEXT,
  file_size INTEGER CHECK(file_size IS NULL OR file_size >= 0),
  uploaded_by INTEGER REFERENCES users(id),
  uploaded_at TEXT DEFAULT iso_now(),
  verified_by INTEGER REFERENCES users(id),
  verified_at TEXT,
  rejection_reason TEXT,
  created_at TEXT DEFAULT iso_now()
);


-- Finance's queue joins this on and sorts pending proofs oldest-first.
-- order_id already has a unique index from the UNIQUE constraint, so the
-- per-order lookup on the order page needs nothing extra.
CREATE INDEX IF NOT EXISTS idx_payment_proofs_status ON payment_proofs(status, uploaded_at ASC);

-- The customer autocomplete searches ~95k rows with LIKE. SQLite's LIKE is
-- case-insensitive for ASCII by default; Postgres's is NOT. Those queries must
-- become ILIKE during the port or search quietly stops matching — this index
-- supports the case-insensitive form so it does not become a full scan.
CREATE INDEX IF NOT EXISTS idx_customers_name_lower ON customers(LOWER(name));
CREATE INDEX IF NOT EXISTS idx_products_name_lower ON products(LOWER(name));

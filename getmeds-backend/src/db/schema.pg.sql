  file_type TEXT NOT NULL DEFAULT 'payment_proof' CHECK(file_type IN ('payment_proof','other','purchase_order','gl','prescription','id')),
  status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','verified','rejected')),

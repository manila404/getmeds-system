-- ── Sep 10, 2026: who owns the Sales Orders imported from Zoho ──────────────
--
-- 60,817 orders came in from Zoho carrying a free-text `salesperson` string
-- and no idea which system account it belongs to. This table is the record of
-- that decision, made by a human, once per distinct Zoho string.
--
-- Why a table and not a one-off reassignment script:
--
--   * Later imports self-attribute. A decision made today applies to Sales
--     Orders pulled next month with no re-review.
--   * It is reversible. Change a row, re-apply, done.
--   * It is auditable. "Why does this rep own this order" has an answer with a
--     name and a date on it.
--
-- Why the decision is not computed: the strings are dirty in ways that make
-- automatic matching actively dangerous. Real examples from the live org —
-- 'MSA I WENDY MAE' uses a capital I rather than a pipe; 'MSA GILBERT DELA
-- CRUZ' has no separator at all; 'MSA | Dona Mae Lebumfacil' and
-- 'B2B |  DONA MAE LEBUMFACIL' are one person under two divisions. Normalise
-- hard enough to catch those and 'HOS | MANILA VACANT' starts looking like
-- 'HOS | Aaron Manila', which would hand one rep another's history. The system
-- suggests; a person decides.
-- ---------------------------------------------------------------------------
-- Sep 11, 2026: which orders a MANAGEMENT user may see and act on.
--
-- Until now every management user saw every order. The business runs three
-- managers with different remits: one owning the whole approval queue, and two
-- who each cover their own divisions.
--
-- A row here GRANTS visibility. There is no deny rule, and no row means no
-- access -- see services/orderScopeService.js for why this fails closed rather
-- than treating "nothing configured" as "no restrictions".
-- ---------------------------------------------------------------------------
-- ---------------------------------------------------------------------------
-- Sep 11, 2026: admin accounts cannot be deleted, deactivated, or demoted.
--
-- Enforced in the DATABASE rather than only in the API because the API is not
-- the only way in. Every repair and provisioning script in scripts/ connects
-- with the same credentials and can issue any UPDATE or DELETE it likes -- one
-- of them removed two user rows earlier today. A rule that only lives in a
-- controller protects the one path somebody remembered to guard.
--
-- Three things are blocked, and the third is the one that gets missed: an
-- admin demoted to another role is not "deactivated" anywhere in the audit
-- trail, but the access is just as gone.
--
-- ESCAPE HATCH: a session that genuinely needs to (offboarding a departing
-- admin) can set the flag below first. It has to be typed on purpose, which is
-- the point -- accidents and stray scripts do not set session variables.
--
--   BEGIN;
--     SET LOCAL app.allow_admin_change = 'on';
--     UPDATE users SET is_active = 0 WHERE id = 1;
--   COMMIT;
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION protect_admin_accounts() RETURNS trigger AS $protect$
BEGIN
  -- Deliberate, per-transaction override. `true` as the second argument makes
  -- current_setting return NULL instead of erroring when the flag was never
  -- set, which is the normal case.
  IF current_setting('app.allow_admin_change', true) = 'on' THEN
    RETURN COALESCE(NEW, OLD);
  END IF;

  -- A TEST admin is not the system's administrator. Test Mode creates and
  -- tears down its own accounts (is_test_account = 1, see
  -- controllers/test.controller.js), and blocking that would make the teardown
  -- fail rather than make anything safer -- a real production admin always has
  -- is_test_account = 0.
  IF COALESCE(OLD.is_test_account, 0) = 1 THEN
    RETURN COALESCE(NEW, OLD);
  END IF;

  IF TG_OP = 'DELETE' THEN
    IF OLD.role = 'admin' THEN
      RAISE EXCEPTION 'Admin accounts cannot be deleted. Set app.allow_admin_change to override.'
        USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN OLD;
  END IF;

  IF OLD.role = 'admin' THEN
    IF NEW.is_active = 0 THEN
      RAISE EXCEPTION 'Admin accounts cannot be deactivated. Set app.allow_admin_change to override.'
        USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF NEW.role <> 'admin' THEN
      RAISE EXCEPTION 'An admin account cannot be changed to another role. Set app.allow_admin_change to override.'
        USING ERRCODE = 'insufficient_privilege';
    END IF;
  END IF;

  RETURN NEW;
END;
$protect$ LANGUAGE plpgsql;

-- Dropped and recreated rather than CREATE IF NOT EXISTS: this file is applied
-- in full on every migration, and a trigger definition that changed would
-- otherwise be ignored on databases that already have the old one.
DROP TRIGGER IF EXISTS trg_protect_admin_update ON users;
CREATE TRIGGER trg_protect_admin_update
  BEFORE UPDATE ON users
  FOR EACH ROW EXECUTE FUNCTION protect_admin_accounts();

DROP TRIGGER IF EXISTS trg_protect_admin_delete ON users;
CREATE TRIGGER trg_protect_admin_delete
  BEFORE DELETE ON users
  FOR EACH ROW EXECUTE FUNCTION protect_admin_accounts();


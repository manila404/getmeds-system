#!/usr/bin/env node
'use strict';

/**
 * Targets of territories nobody holds, from the sales sheet's Oct to Dec 2026 targets. Oct 21, 2026.
 *
 * WHY: scripts/apply-targets-script.js (targets-2026-q4/) gave each sheet row to the person
 * who holds that territory and SKIPPED the rows for vacant territories, so about PHP 7.3M a
 * month never reached the company target. territory_targets (schema.pg.sql) holds them.
 *
 * WHAT IT DOES: reads the sheet and the live structure in a READ ONLY transaction, sorts the
 * rows that no person received, and WRITES A .sql FILE. It changes nothing itself; the SQL is
 * run by hand in the Supabase SQL Editor.
 *
 *   vacant       the territory is marked vacant                      -> in the SQL
 *   no account   the territory exists but no account holds it        -> listed, NOT in the SQL
 *   no territory the sheet row matches no territory                  -> listed, NOT in the SQL
 *
 * "no account" and "no territory" rows are left for a human: a person may already carry that
 * target under another name (B2C | CJ Gutierrez), and counting it twice is worse than missing it.
 * Add --include-unheld to put the "no account" rows in the SQL too.
 *
 *   node scripts/vacant-territory-targets.js <sheet.csv> [out.sql] [--include-unheld]
 */
require('dotenv').config();
const fs = require('fs');
const { Pool } = require('pg');

const csvPath = process.argv[2];
const outPath = process.argv[3] && !process.argv[3].startsWith('--') ? process.argv[3] : 'territory-targets-oct-dec-2026.sql';
const INCLUDE_UNHELD = process.argv.includes('--include-unheld');
if (!csvPath) { console.error('usage: node scripts/vacant-territory-targets.js <sheet.csv> [out.sql] [--include-unheld]'); process.exit(1); }

const parse = (t) => { const L = t.trim().split(/\r?\n/); L.shift(); return L.map((l) => { const m = l.match(/^([^,]*),("([^"]*)"|[^,]*),([^,]*),([^,]*),([^,]*)$/); return { hq: m[3] ?? m[2], v: { '2026-10': +m[4], '2026-11': +m[5], '2026-12': +m[6] } }; }); };
const key = (s) => String(s || '').toLowerCase().replace(/\(.*?\)/g, '').replace(/\bi\b/g, '|').replace(/[^a-z0-9]/g, '');
const norm = (s) => String(s || '').toLowerCase().replace(/\s+/g, ' ').trim();
const MANUAL = { 'urocare cebu': 'URO | CEBU' };                              // same as apply-targets-script.js
const PERSON = { 'telesales micah': 1, 'uro | kalaw': 1 };                    // given to a named person there
const MONTHS = ['2026-10', '2026-11', '2026-12'];
const sq = (s) => `'${String(s).replace(/'/g, "''")}'`;

(async () => {
  const pool = new Pool({ connectionString: process.env.DATABASE_URL, max: 1 });
  const c = await pool.connect();
  try {
    await c.query('BEGIN READ ONLY');
    const terrs = (await c.query('SELECT zoho_salesperson, zoho_alias, is_vacant FROM sales_territories')).rows;
    const links = (await c.query(`SELECT us.salesperson FROM user_salespersons us JOIN users u ON u.id = us.user_id
                                   WHERE u.is_active = 1 AND u.role IN ('medrep','team_lead')`)).rows;
    await c.query('ROLLBACK');

    const byKey = new Map(); for (const t of terrs) for (const n of [t.zoho_salesperson, t.zoho_alias]) if (n) byKey.set(key(n), t);
    const byName = new Map(terrs.map((t) => [t.zoho_salesperson, t]));
    const held = new Set(links.map((l) => norm(l.salesperson)));

    const vacant = []; const unheld = []; const noTerritory = [];
    for (const r of parse(fs.readFileSync(csvPath, 'utf8'))) {
      if (PERSON[norm(r.hq)]) continue;                                       // went to a person
      const t = MANUAL[norm(r.hq)] ? byName.get(MANUAL[norm(r.hq)]) : byKey.get(key(r.hq));
      if (!t) { noTerritory.push({ r, t: null }); continue; }
      // A vacant territory counts even if a lead covers it as a secondary salesperson (the apply
      // script skipped it, so nobody received that target). A territory that is NOT vacant and is
      // held went to its holder.
      const names = [t.zoho_salesperson, t.zoho_alias].filter(Boolean).map(norm);
      if (!t.is_vacant && names.some((n) => held.has(n))) continue;
      (t.is_vacant ? vacant : unheld).push({ r, t });
    }

    const rows = INCLUDE_UNHELD ? [...vacant, ...unheld] : vacant;
    const sql = [
      '-- Targets of territories nobody holds, Oct to Dec 2026 (from the sales sheet). Run once in the Supabase SQL Editor.',
      '-- Safe to run again: a row is replaced, never added twice.',
      `CREATE TABLE IF NOT EXISTS territory_targets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label TEXT NOT NULL,
  territory_id INTEGER REFERENCES sales_territories(id) ON DELETE SET NULL,
  month TEXT NOT NULL CHECK (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  target_php DOUBLE PRECISION NOT NULL CHECK (target_php >= 0),
  set_by INTEGER REFERENCES users(id),
  set_at TEXT DEFAULT iso_now(),
  UNIQUE (label, month)
);
CREATE INDEX IF NOT EXISTS idx_territory_targets_month ON territory_targets(month);`,
      ''
    ];
    for (const { r, t } of rows) {
      for (const m of MONTHS) {
        sql.push(`INSERT INTO territory_targets (label, territory_id, month, target_php)
VALUES (${sq(r.hq)}, (SELECT id FROM sales_territories WHERE zoho_salesperson = ${sq(t.zoho_salesperson)} LIMIT 1), ${sq(m)}, ${r.v[m]})
ON CONFLICT (label, month) DO UPDATE SET target_php = EXCLUDED.target_php, territory_id = EXCLUDED.territory_id, set_at = iso_now();`);
      }
    }
    fs.writeFileSync(outPath, sql.join('\n') + '\n');

    const tot = (arr, m) => arr.reduce((a, x) => a + x.r.v[m], 0);
    const peso = (n) => Math.round(n).toLocaleString('en-PH');
    console.log(`In the SQL (${rows.length} territories): Oct ${peso(tot(rows, '2026-10'))}  Nov ${peso(tot(rows, '2026-11'))}  Dec ${peso(tot(rows, '2026-12'))}`);
    for (const { r, t } of rows) console.log(`  + ${r.hq}  ->  ${t.zoho_salesperson}  Oct ${peso(r.v['2026-10'])}`);
    if (!INCLUDE_UNHELD) {
      console.log(`\nNOT in the SQL, for you to decide (${unheld.length + noTerritory.length} rows, Oct ${peso(tot(unheld, '2026-10') + tot(noTerritory, '2026-10'))}):`);
      for (const { r, t } of unheld) console.log(`  ? ${r.hq}  (territory ${t.zoho_salesperson} exists, no account holds it)  Oct ${peso(r.v['2026-10'])}`);
      for (const { r } of noTerritory) console.log(`  ? ${r.hq}  (matches no territory)  Oct ${peso(r.v['2026-10'])}`);
    }
    console.log(`\nWrote ${outPath}. Nothing was changed in the database.`);
  } catch (e) { await c.query('ROLLBACK').catch(() => {}); throw e; } finally { c.release(); await pool.end(); }
})().catch((e) => { console.error('ERR', e.message); process.exit(1); });
